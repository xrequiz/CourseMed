export function resolvePrompt(promptId) {
  if (typeof promptId !== "string" || promptId.length > 60) return null;
  if (STATIC[promptId]) return { system: STATIC[promptId] };

  const sep = promptId.indexOf(":");
  if (sep === -1) return null;
  const kind = promptId.slice(0, sep);
  const key = promptId.slice(sep + 1);

  if (kind === "sim-actor" && SIM[key]) {
    return { system: `${ACTOR_PREAMBLE}\n\nתדריך הדמות: ${SIM[key].brief}` };
  }
  if (kind === "sim-debrief" && SIM[key]) {
    const s = SIM[key];
    return {
      system: `${SIM_DEBRIEF_BASE}\n\nהמשימה שניתנה למועמד: ${s.task}\nתדריך השחקן (סמוי מהמועמד): ${s.brief}`,
    };
  }
  if (kind === "interview" && INTERVIEWS[key]) return { system: INTERVIEWS[key].system };
  if (kind === "interview-feedback" && INTERVIEWS[key]) return { system: INTERVIEWS[key].feedback };
  return null;
}
